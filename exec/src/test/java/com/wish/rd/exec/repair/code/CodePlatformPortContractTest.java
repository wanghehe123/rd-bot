package com.wish.rd.exec.repair.code;

import com.wish.rd.exec.repair.execution.RepairArtifact;
import com.wish.rd.exec.repair.execution.RepairArtifactType;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class CodePlatformPortContractTest {

    @Test
    void shouldRejectBlankRequiredCommandFields() {
        assertThrows(IllegalArgumentException.class, () -> command(" ", "order", "main", "repair/task-1001"));
        assertThrows(IllegalArgumentException.class, () -> command("acme", "", "main", "repair/task-1001"));
        assertThrows(IllegalArgumentException.class, () -> command("acme", "order", null, "repair/task-1001"));
        assertThrows(IllegalArgumentException.class, () -> command("acme", "order", "main", "\t"));
    }

    @Test
    void shouldNormalizeCommandOptionalFieldsAndCopyArtifacts() {
        RepairArtifact patchArtifact = new RepairArtifact(
                RepairArtifactType.PATCH_DIFF,
                "patch.diff",
                "file:///tmp/patch.diff",
                "patch",
                Map.of("bytes", "128")
        );
        List<RepairArtifact> artifacts = new ArrayList<>();
        artifacts.add(patchArtifact);
        Map<String, String> metadata = new HashMap<>();
        metadata.put("source", "executor");
        metadata.put("nullable", null);

        CreatePullRequestCommand command = new CreatePullRequestCommand(
                " acme ",
                " order ",
                " main ",
                " repair/task-1001 ",
                null,
                null,
                artifacts,
                metadata
        );
        artifacts.clear();
        metadata.put("source", "changed");

        assertEquals("acme", command.repoOwner());
        assertEquals("order", command.repoName());
        assertEquals("main", command.baseBranch());
        assertEquals("repair/task-1001", command.workBranch());
        assertEquals("", command.title());
        assertEquals("", command.prBody());
        assertEquals(List.of(patchArtifact), command.artifactReferences());
        assertEquals("executor", command.metadata().get("source"));
        assertEquals("", command.metadata().get("nullable"));
        assertThrows(UnsupportedOperationException.class, () -> command.artifactReferences().add(patchArtifact));
        assertThrows(UnsupportedOperationException.class, () -> command.metadata().put("other", "value"));
        assertThrows(IllegalArgumentException.class, () -> new CreatePullRequestCommand(
                "acme",
                "order",
                "main",
                "repair/task-1001",
                "Fix order failure",
                "Generated by RD-Bot repair executor.",
                List.of(),
                Map.of("source", "first", " source ", "second")
        ));
    }

    @Test
    void shouldNormalizePullRequestResultMetadata() {
        Map<String, String> metadata = new HashMap<>();
        metadata.put("number", "42");
        metadata.put("nullable", null);

        PullRequestResult result = new PullRequestResult(
                " https://github.example.local/acme/order/pull/42 ",
                " 42 ",
                metadata
        );
        metadata.put("number", "changed");

        assertEquals("https://github.example.local/acme/order/pull/42", result.pullRequestUrl());
        assertEquals("42", result.pullRequestNumber());
        assertEquals("42", result.metadata().get("number"));
        assertEquals("", result.metadata().get("nullable"));
        assertThrows(UnsupportedOperationException.class, () -> result.metadata().put("other", "value"));
        assertThrows(IllegalArgumentException.class, () -> new PullRequestResult(
                "https://github.example.local/acme/order/pull/42",
                "42",
                Map.of("number", "42", " number ", "043")
        ));
    }

    @Test
    void shouldRecordCommandAndReturnDeterministicPrUrl() {
        RecordingCodePlatformPort codePlatform = new RecordingCodePlatformPort();
        CreatePullRequestCommand command = command("acme", "order", "main", "repair/task-1001");

        PullRequestResult result = codePlatform.createPullRequest(command);

        assertEquals("https://github.example.local/acme/order/pull/repair-task-1001", result.pullRequestUrl());
        assertEquals("repair-task-1001", result.pullRequestNumber());
        assertEquals("acme/order", result.metadata().get("repository"));
        assertEquals(List.of(command), codePlatform.commands());
    }

    @Test
    void shouldKeepProductionCodePlatformPortProviderNeutral() throws IOException {
        try (Stream<Path> files = Files.walk(Path.of("src/main/java/com/wish/rd/exec/repair/code"))) {
            List<Path> javaFiles = files
                    .filter(path -> path.toString().endsWith(".java"))
                    .toList();
            assertFalse(javaFiles.isEmpty());
            for (Path javaFile : javaFiles) {
                String source = Files.readString(javaFile).toLowerCase(Locale.ROOT);
                assertFalse(source.contains("github"), javaFile.toString());
                assertFalse(source.contains("token"), javaFile.toString());
                assertFalse(source.contains("installation"), javaFile.toString());
                assertFalse(source.contains("rest"), javaFile.toString());
                assertFalse(source.contains("docker"), javaFile.toString());
                assertFalse(source.contains("feishu"), javaFile.toString());
            }
        }
    }

    private static CreatePullRequestCommand command(
            String repoOwner,
            String repoName,
            String baseBranch,
            String workBranch
    ) {
        return new CreatePullRequestCommand(
                repoOwner,
                repoName,
                baseBranch,
                workBranch,
                "Fix order failure",
                "Generated by RD-Bot repair executor.",
                List.of(),
                Map.of()
        );
    }

    private static final class RecordingCodePlatformPort implements CodePlatformPort {

        private final List<CreatePullRequestCommand> commands = new ArrayList<>();

        @Override
        public PullRequestResult createPullRequest(CreatePullRequestCommand command) {
            commands.add(command);
            String pullRequestNumber = command.workBranch().replace('/', '-');
            return new PullRequestResult(
                    "https://github.example.local/%s/%s/pull/%s".formatted(
                            command.repoOwner(),
                            command.repoName(),
                            pullRequestNumber
                    ),
                    pullRequestNumber,
                    Map.of("repository", command.repoOwner() + "/" + command.repoName())
            );
        }

        private List<CreatePullRequestCommand> commands() {
            return List.copyOf(commands);
        }
    }
}
